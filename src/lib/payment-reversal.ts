import type { BillingDocument, BillingPayment, Expense, WCTransaction } from '@/types';

/**
 * Finds the Working Capital entries created when a payment was recorded,
 * so that deleting the payment can remove them (and, through the reducer,
 * reverse Retained Profit and the Working Capital balance).
 *
 * New payments carry a `paymentId` tag. Older payments are matched by
 * invoice number + date + amount. `claimed` stops two identical same-day
 * payments from matching the same ledger lines.
 */
export function findPaymentWcTxIds(
  txs: WCTransaction[],
  invoice: BillingDocument,
  payment: BillingPayment,
  claimed: Set<string>,
): { ids: string[]; complete: boolean } {
  const tagged = txs.filter(t => (t as any).paymentId === payment.id && !claimed.has(t.id));
  if (tagged.length > 0) {
    tagged.forEach(t => claimed.add(t.id));
    return { ids: tagged.map(t => t.id), complete: true };
  }

  const amt = payment.mwkEquivalent;
  const mine = txs.filter(t =>
    t.autoGenerated && !claimed.has(t.id) && t.date === payment.date &&
    ((t.description || '').includes(invoice.number) || t.reference === invoice.number));

  const ids: string[] = [];
  const inflow = mine.find(t => t.type === 'inflow' && t.category === 'client_payment' && t.amount === amt);
  if (inflow) ids.push(inflow.id);

  const outs = mine.filter(t => t.type === 'outflow' && (t.category === 'client_to_retained' || t.category === 'bonus_to_bank'));
  let outMatch: WCTransaction[] = [];
  const single = outs.find(t => t.amount === amt);
  if (single) outMatch = [single];
  else {
    for (let i = 0; i < outs.length && outMatch.length === 0; i++) {
      for (let j = i + 1; j < outs.length; j++) {
        if (outs[i].amount + outs[j].amount === amt) { outMatch = [outs[i], outs[j]]; break; }
      }
    }
  }
  ids.push(...outMatch.map(t => t.id));
  ids.forEach(id => claimed.add(id));
  return { ids, complete: !!inflow && outMatch.length > 0 };
}

/** Invoice status once some payments are removed. */
export function statusAfterPayments(invoice: BillingDocument, remaining: BillingPayment[]): 'paid' | 'partial' | 'sent' {
  const paidMwk = remaining.reduce((s, p) => s + p.mwkEquivalent, 0);
  const dueMwk = invoice.total * ((invoice as any).exchangeRate || 1);
  if (remaining.length > 0 && paidMwk >= dueMwk) return 'paid';
  return paidMwk > 0 ? 'partial' : 'sent';
}

/** WC outflow created by a project cost recorded before the project-money rule. */
export function findLegacyExpenseWcTxId(txs: WCTransaction[], expense: Expense): string | undefined {
  return txs.find(t =>
    t.autoGenerated && t.type === 'outflow' && t.category === 'project_expense' &&
    t.amount === expense.amount && t.date === expense.date &&
    (t.description || '').startsWith(expense.description))?.id;
}
