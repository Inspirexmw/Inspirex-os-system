import type { AppState } from '@/types';
import type { ActivityItem } from '@/components/ui/activity-feed';

/**
 * Derives a timeline of recent financial events from app state.
 * Pulls from WC ledger, Bonus Bank ledger, projects, billing payments, and expenses.
 * Returns newest first, capped at `limit`.
 */
export function buildActivityFeed(state: AppState, limit = 12): ActivityItem[] {
  const items: ActivityItem[] = [];

  // 1. Project creations
  for (const p of state.projects || []) {
    items.push({
      id: `proj-${p.id}`,
      kind: 'project_created',
      title: `Project saved — ${p.name}`,
      detail: `${p.type} · ${p.month}`,
      amount: p.revenue,
      at: p.createdAt,
    });
  }

  // 2. Billing payments
  for (const doc of state.billing?.documents || []) {
    if (doc.type !== 'invoice' && doc.type !== 'receipt') continue;
    const client = (state.billing?.clients || []).find((c: any) => c.id === doc.clientId);
    for (const pmt of doc.payments || []) {
      items.push({
        id: `pmt-${pmt.id}`,
        kind: 'payment_received',
        title: `Payment received — ${doc.number}`,
        detail: client?.name || 'Client',
        amount: pmt.mwkEquivalent || pmt.amount,
        at: pmt.date + 'T12:00:00.000Z',
      });
    }
  }

  // 3. WC outflows (categorize: stipend payroll, expenses, transfers)
  for (const tx of state.wcTransactions || []) {
    if (tx.autoGenerated && (tx.category === 'bonus_to_bank' || tx.category === 'client_to_retained' || tx.category === 'client_payment')) {
      // Skip the routing pairs — too noisy; payment_received already covers the inflow
      continue;
    }
    if (tx.type === 'outflow') {
      items.push({
        id: `wc-${tx.id}`,
        kind: tx.category === 'payroll' || tx.category === 'salary' ? 'stipend_paid'
            : tx.category === 'project_expense' ? 'expense'
            : 'transfer',
        title: tx.description,
        amount: tx.amount,
        at: tx.date + 'T12:00:00.000Z',
      });
    } else if (tx.type === 'inflow' && (tx.category === 'profit_to_wc_operations' || tx.category === 'profit_to_wc_capital' || tx.category === 'manual_topup')) {
      items.push({
        id: `wc-${tx.id}`,
        kind: 'transfer',
        title: tx.description,
        amount: tx.amount,
        at: tx.date + 'T12:00:00.000Z',
      });
    }
  }

  // 4. Score saves (from task projects)
  for (const tp of state.taskProjects || []) {
    if (tp.scores && tp.scores.length > 0) {
      items.push({
        id: `scores-${tp.id}`,
        kind: 'scores_saved',
        title: `Scores saved — ${tp.name}`,
        detail: `${tp.scores.length} member${tp.scores.length !== 1 ? 's' : ''}`,
        at: (tp as any).updatedAt || tp.createdAt,
      });
    }
  }

  // Sort newest first, cap
  return items
    .sort((a, b) => new Date(b.at).getTime() - new Date(a.at).getTime())
    .slice(0, limit);
}

/**
 * Derives a 6-month cash-flow series for the area chart.
 * Approximates WC/BB/RP balances over time using transaction history.
 */
export function buildCashFlowSeries(state: AppState, months = 6) {
  const today = new Date();
  const series: Array<{ month: string; wc: number; bonusBank: number; retainedProfit: number }> = [];

  for (let i = months - 1; i >= 0; i--) {
    const d = new Date(today.getFullYear(), today.getMonth() - i, 1);
    const monthStr = d.toISOString().slice(0, 7);
    // End of this month — find balanceAfter of the last tx in that month, fall back to running total
    const endOfMonth = new Date(d.getFullYear(), d.getMonth() + 1, 0).toISOString().slice(0, 10);

    const wcTxs = (state.wcTransactions || []).filter(t => t.date <= endOfMonth);
    const wc = wcTxs.length > 0
      ? wcTxs[wcTxs.length - 1].balanceAfter
      : 0;

    const bbTxs = (state.bonusBankTransactions || []).filter(t => t.date <= endOfMonth);
    const bonusBank = bbTxs.length > 0
      ? bbTxs[bbTxs.length - 1].balanceAfter
      : 0;

    // Retained profit needs derivation — sum client_to_retained amounts up to date,
    // minus profit_to_wc_* withdrawals.
    let retainedProfit = 0;
    for (const tx of state.wcTransactions || []) {
      if (tx.date > endOfMonth) continue;
      if (tx.category === 'client_to_retained') retainedProfit += tx.amount;
      else if (tx.category === 'profit_to_wc_operations' || tx.category === 'profit_to_wc_capital') retainedProfit -= tx.amount;
    }
    retainedProfit = Math.max(0, retainedProfit);

    series.push({ month: monthStr, wc, bonusBank, retainedProfit });
  }

  return series;
}
